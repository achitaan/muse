"""Independent integer-owner oracle and float-error envelope; no GPU timing."""
import ast
import hashlib
import json
from pathlib import Path
import re

import numpy as np

from build_moe_schedq import BASE_SHA, OLD, NEW, ROOT


def cuda_literal(raw):
    tree = ast.parse(raw)
    node = next(n for n in tree.body if isinstance(n, ast.Assign)
                and any(isinstance(t, ast.Name) and t.id == 'CUDA_SRC' for t in n.targets))
    return tree, node, ast.literal_eval(node.value)


def audit():
    raw = (ROOT / '.tools/moe-schedq-variant.py').read_bytes()
    base = (ROOT / 'best/moe_verified.py').read_bytes()
    assert hashlib.sha256(base).hexdigest() == BASE_SHA
    bt, bn, bc = cuda_literal(base)
    ct, cn, cc = cuda_literal(raw)
    assert cc.count(NEW) == 1 and cc.replace(NEW, OLD, 1) == bc
    cn.value = ast.Constant(bc)
    assert ast.dump(ct, include_attributes=False) == ast.dump(bt, include_attributes=False)
    ca, cb = [[int(v) for v in re.search(r'#define OKC_WGS' + x + r' ([\d, ]+)', bc)[1].split(',')]
              for x in ('A', 'B')]
    assert len(ca) == len(cb) == 8 and all(0 < v <= 255 for v in ca + cb)
    max_jobs, max_grid = 32 + (384 * 8) // 64 + 8, 160
    max_total = max_jobs * 512 * 255
    assert max_total * max_grid < 2**32
    # JMAX=88 and grid<=160 bound the integer comparisons away from overflow.
    # Correctness does not require a one-step estimate error: the unchanged
    # loops monotonically advance/decrease c to the exact owner of xe-1.
    rng = np.random.default_rng(20261028)
    distributions = [(i,) for i in range(1, 65)]
    for m in (17, 32, 33, 64, 127, 128, 256, 257, 383, 384):
        # Include duplicates: up to all eight entries per token on one expert.
        for probs in (np.ones(32)/32, np.r_[0.8, np.ones(31)*0.2/31], np.r_[1., np.zeros(31)]):
            for _ in range(3):
                counts = rng.multinomial(m * 8, probs)
                fat = [min(64, int(c) - q) for c in counts if c > 8 for q in range(0, int(c), 64)]
                skinny = [int(c) for c in counts if 0 < c <= 8]
                distributions.append(tuple(fat + skinny))
    # Conservative capacity edge; not assumed to be generated by valid routes.
    distributions.extend([(64,) * max_jobs, (1,) * max_jobs, tuple(range(1, 65))])
    checked, largest_correction = 0, 0
    for counts in distributions:
        assert len(counts) <= max_jobs
        for pb, costs in enumerate((ca, cb)):
            sizes = np.array([costs[(c+7)//8-1] * (512 >> pb) for c in counts], dtype=np.int64)
            prefix = np.r_[0, np.cumsum(sizes)]
            total = int(prefix[-1])
            # wgs_cta_of is called on unit starts (16-stage boundaries).
            xe = np.concatenate([prefix[j] + (np.arange(0, 512 >> pb, 16, dtype=np.int64) + 1)
                                 * costs[(c+7)//8-1] for j, c in enumerate(counts)])
            for grid in range(1, max_grid+1):
                # Independent oracle: largest c such that floor(total*c/G)<xe.
                expected = np.minimum((xe * grid - 1) // total, grid - 1)
                old = ((xe - 1) * grid) // total
                nominal = ((xe - 1).astype(np.float32) * np.float32(grid)) / np.float32(total)
                for error_direction in (-1, 0, 1):
                    estimate = nominal.copy()
                    if error_direction:
                        toward = np.float32(-np.inf if error_direction < 0 else np.inf)
                        # NVIDIA documents <=2 ULP for this ordinary positive domain.
                        estimate = np.nextafter(np.nextafter(estimate, toward), toward)
                    c = np.minimum(estimate.astype(np.int64), grid - 1)
                    before = c.copy()
                    up = (c+1 < grid) & (total * (c+1) // grid < xe)
                    while np.any(up):
                        c[up] += 1
                        up = (c+1 < grid) & (total * (c+1) // grid < xe)
                    down = (c > 0) & (total*c // grid >= xe)
                    while np.any(down):
                        c[down] -= 1
                        down = (c > 0) & (total*c // grid >= xe)
                    assert np.array_equal(c, expected)
                    largest_correction = max(largest_correction, int(np.max(np.abs(c-before))))
                    checked += c.size
                # The original quotient needs the same correction at fractional boundaries.
                assert np.all(np.abs(old - expected) <= 1)
    record = {'source_sha256': hashlib.sha256(raw).hexdigest(), 'base_sha256': BASE_SHA,
              'original_module_ast_recovered': True, 'cuda_one_expression_reversible': True,
              'integer_owner_comparisons': checked, 'routing_count_distributions': len(distributions),
              'grid_range': [1, max_grid], 'max_integer_product': max_total*max_grid,
              'float_intrinsic_error_envelope_ulp': [-2, 2], 'largest_correction': largest_correction,
              'all_owners_exact': True, 'seed': 20261028,
              'scope_limit': 'CPU integer/control proof and float32 envelope; CUDA compilation and GPU numerics/timing unverified'}
    (ROOT / '.tools/moe-schedq-cpu-audit.json').write_text(json.dumps(record, indent=2) + '\n', encoding='utf8')
    print(json.dumps(record))


if __name__ == '__main__':
    audit()
